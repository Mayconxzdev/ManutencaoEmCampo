import React, { useState, useEffect } from 'react';















import axios from 'axios';
import { useNavigate } from 'react-router-dom';







import ExecutarOM from './ExecutarOM';















import {















  CheckSquare,















  Camera,















  AlertOctagon,















  RefreshCw,















  Play,















  CheckCircle,















  Clock,















  AlertTriangle,
  QrCode,






























} from 'lucide-react';































interface OrderItem {















  id: string;















  item_id: string;















  status: string;





































  notes: string;















}































interface Order {















  id: string;















  friendly_number: number;















  priority: string;
  execution_status?: string;
  needs_review?: boolean;
  review_decision?: string | null;















  status: string;















  planned_date: string;















  checklist_version_id: string;















  asset: {















    id: string;















    patrimonio: string;















    description: string;











    manufacturer?: string | null;











    model?: string | null;











    show_in_daily_list?: boolean;











    sector?: { name?: string | null } | null;















    is_operable: boolean;















  };















  items: OrderItem[];















  notes?: string;















}






























































const API_URL = window.location.port === '5173'















  ? `http://${window.location.hostname}:8000`















  : window.location.origin;































export default function Hoje() {

  const navigate = useNavigate();















  const [orders, setOrders] = useState<Order[]>([]);



  const [executingOrderId, setExecutingOrderId] = useState<string | null>(null);















  const [assets, setAssets] = useState<any[]>([]);






























  const [loading, setLoading] = useState(true);















  const [error, setError] = useState('');































  const operatorName = sessionStorage.getItem('mec_operator_name') || 'Operador Padrão';
  const operatorId = sessionStorage.getItem('mec_operator_id') || undefined;































  // Estados para Modais















  const [showIssueModal, setShowIssueModal] = useState(false);
  const [showAllOverdue, setShowAllOverdue] = useState(false);















  const [showSyncSuccess, setShowSyncSuccess] = useState(false);














































  // Campos de Ocorrência















  const [selectedAsset, setSelectedAsset] = useState('');















  const [issueDesc, setIssueDesc] = useState('');















  const [isStopped, setIsStopped] = useState(false);































  // Campos de Fechamento da OM





























































  const fetchTodayData = async () => {















    setLoading(true);















    try {















      const ordersRes = await axios.get(`${API_URL}/orders`);















      setOrders(ordersRes.data);































      const assetsRes = await axios.get(`${API_URL}/assets`);















      setAssets(assetsRes.data);














































      setError('');















    } catch (err) {















      console.error(err);















      setError('Erro ao conectar com a API Backend. Verifique se o servidor está rodando.');















    } finally {















      setLoading(false);















    }















  };































  useEffect(() => {















    fetchTodayData();















  }, []);































  // Filtrar Ordens















  const operationalOrders = orders.filter(
    (order) => order.asset?.show_in_daily_list !== false && !order.needs_review
  );

  const inProgressOrders = operationalOrders.filter(
    (order) => order.status === 'in_progress' || order.execution_status === 'in_progress'
  );

  const todayOrders = operationalOrders.filter(
    (order) => order.status === 'today' || order.status === 'in_progress' || order.execution_status === 'in_progress'
  );

  const readyToStartTodayCount = todayOrders.filter(
    (order) => order.status === 'today' && order.execution_status !== 'in_progress'
  ).length;















  const overdueOrders = operationalOrders.filter(order => order.status === 'overdue');

  const importedPlanningCount = orders.filter(
    (order) => order.needs_review && order.review_decision === 'to_review'
  ).length;

  const operationalAssets = assets.filter(
    (asset: any) => asset.status === 'active' && asset.show_in_daily_list !== false
  );

  const selectedIssueAsset = operationalAssets.find((asset: any) => asset.id === selectedAsset);

  const describeAsset = (asset: Order['asset']) => {
    const manufacturerModel = [asset.manufacturer, asset.model].filter(Boolean).join(' ');
    const sector = asset.sector?.name || 'Setor não informado';
    return [sector, manufacturerModel || 'Marca/modelo não informado'].join(' · ');
  };

  const formatPlannedDate = (value?: string) => {
    if (!value) return 'Data programada a confirmar';
    const date = new Date(`${value.slice(0, 10)}T12:00:00`);
    return Number.isNaN(date.getTime()) ? 'Data programada a confirmar' : date.toLocaleDateString('pt-BR');
  };















  const stoppedAssets = assets.filter(a => !a.is_operable);































  // @ts-ignore



  // @ts-ignore

// @ts-ignore



  // @ts-ignore

  const handleReportIssue = async (e: React.FormEvent) => {















    e.preventDefault();















    if (!selectedAsset || !issueDesc) return;































    try {















      await axios.post(`${API_URL}/issues`, {















        asset_id: selectedAsset,















        description: issueDesc,















        priority: isStopped ? 'critical' : 'high',















        is_operable_affected: isStopped,















        operator_name: operatorName,
        selected_user_id: operatorId















      });































      setShowIssueModal(false);















      setIssueDesc('');















      setIsStopped(false);















      fetchTodayData();















      alert('Problema registrado com sucesso! O ativo foi atualizado.');















    } catch (err) {















      console.error(err);















      alert('Erro ao registrar o problema.');















    }















  };































  const handleReleaseAsset = async (assetId: string) => {















    if (!window.confirm('Confirmar a liberação operacional desta máquina? Todas as ocorrências críticas serão resolvidas.')) {















      return;















    }















    try {















      await axios.post(`${API_URL}/assets/${assetId}/release`, null, {















        params: { operator_name: operatorName, selected_user_id: operatorId }















      });















      fetchTodayData();















      alert('Máquina liberada para operação!');















    } catch (err) {















      console.error(err);















      alert('Erro ao liberar a máquina.');















    }















  };































  const openPaperCmpUpload = () => {
    navigate('/cmp/conferencia');
  };






























































  if (executingOrderId) {















    return (















      <ExecutarOM















        orderId={executingOrderId}















        onCancel={() => setExecutingOrderId(null)}















        onComplete={() => {















          setExecutingOrderId(null);















          fetchTodayData();















        }}















      />















    );















  }































  return (















    <div>















      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '8px' }}>















        <h1>Hoje na Produção</h1>















        <button className="btn btn-secondary" onClick={fetchTodayData} style={{ padding: '8px 16px' }}>















          <RefreshCw size={16} /> Atualizar















        </button>















      </div>















      <p className="subtitle">Painel de controle simplificado da manutenção</p>





      {error && (















        <div style={{ backgroundColor: 'var(--danger-light)', color: 'var(--danger)', padding: '16px', borderRadius: '8px', marginBottom: '24px', fontWeight: '500' }}>















          {error}















        </div>















      )}































      {/* Grid de Semáforo Industrial */}















      <div className="status-grid">















        <div className={`status-indicator ${stoppedAssets.length > 0 ? 'danger' : 'success'}`}>















          <AlertOctagon size={24} />















          <div>















            <div className="status-value">{stoppedAssets.length}</div>















            <div style={{ fontSize: '12px' }}>MÁQUINAS PARADAS</div>















          </div>















        </div>















        <div className="status-indicator warning">















          <Clock size={24} />















          <div>















            <div className="status-value">{overdueOrders.length}</div>















            <div style={{ fontSize: '12px' }}>ATRASADAS</div>















          </div>















        </div>















        <div className="status-indicator primary">















          <Play size={24} />















          <div>















            <div className="status-value">{readyToStartTodayCount}</div>















            <div style={{ fontSize: '12px' }}>PARA INICIAR HOJE</div>















          </div>















        </div>















      </div>































      {importedPlanningCount > 0 && (
        <div className="card" style={{ borderColor: 'var(--warning)', backgroundColor: 'var(--warning-light)', marginBottom: '20px' }}>
          <strong style={{ display: 'block', marginBottom: '4px' }}>Programação inicial aguardando conferência</strong>
          <span style={{ color: 'var(--text-muted)', fontSize: '14px' }}>
            {importedPlanningCount} registro(s) importado(s) da planilha foram preservados para revisão. Eles não contam como manutenção atrasada e não aparecem na fila de execução.
          </span>
        </div>
      )}

      {/* Se houver máquinas paradas, exibir painel de liberação imediata */}















      {stoppedAssets.length > 0 && (















        <div className="card" style={{ borderColor: 'var(--danger)', backgroundColor: 'var(--danger-light)', marginBottom: '32px' }}>















          <h3 style={{ color: 'var(--danger)', fontSize: '16px', fontWeight: '700', display: 'flex', alignItems: 'center', gap: '8px', marginBottom: '12px' }}>















            <AlertTriangle size={18} /> ATENÇÃO: Máquinas Paradas na Fábrica















          </h3>















          <div style={{ display: 'flex', flexDirection: 'column', gap: '10px' }}>















            {stoppedAssets.map(a => (















              <div key={a.id} style={{















                backgroundColor: 'white',















                padding: '12px 16px',















                borderRadius: '8px',















                display: 'flex',















                justifyContent: 'space-between',















                alignItems: 'center',















                boxShadow: 'var(--shadow-sm)'















              }}>















                <div>















                  <strong style={{ fontSize: '15px' }}>{a.patrimonio} - {a.description}</strong>















                  <div style={{ fontSize: '12px', color: 'var(--text-muted)' }}>Setor: {a.sector?.name || 'Geral'}</div>















                </div>















                <button















                  className="btn btn-primary"















                  style={{ backgroundColor: 'var(--danger)', fontSize: '13px', padding: '6px 12px' }}















                  onClick={() => handleReleaseAsset(a.id)}















                >















                  Liberar Operação (Manual)















                </button>















              </div>















            ))}















          </div>















        </div>















      )}































      {/* Grid de Ações Rápidas */}















      <h2 style={{ marginBottom: '20px', fontSize: '18px', fontWeight: '600' }}>Ações Rápidas</h2>















      <div className="action-grid">















        <button className="action-btn-large" onClick={() => navigate('/qr/escanear')}>
          <QrCode />
          <div>
            <div className="action-title">Escanear QR</div>
            <div className="action-desc">Abrir câmera para OM, ativo ou CMP impresso</div>
          </div>
        </button>

        <button className="action-btn-large" onClick={() => navigate('/checklists/iniciar')}>















          <CheckSquare />















          <div>















            <div className="action-title">Iniciar Checklist Digital</div>















            <div className="action-desc">Fazer o checklist tocando no celular</div>















          </div>















        </button>































        <button className="action-btn-large" onClick={openPaperCmpUpload}>















          <Camera />















          <div>















            <div className="action-title">Digitalizar CMP em papel</div>















            <div className="action-desc">Processar formulário físico preenchido</div>















          </div>















        </button>































        <button className="action-btn-large" onClick={() => setShowIssueModal(true)} style={{ borderColor: 'var(--danger)' }}>















          <AlertOctagon style={{ color: 'var(--danger)' }} />















          <div>















            <div className="action-title" style={{ color: 'var(--danger)' }}>Informar problema ou risco</div>















            <div className="action-desc">Registre defeito, risco, parada ou necessidade de manutenção</div>















          </div>















        </button>















      </div>































      {/* Lista de Ordens Importantes */}















      <h2 style={{ marginBottom: '16px', fontSize: '18px', fontWeight: '600', display: 'flex', justifyContent: 'space-between', gap: '12px', flexWrap: 'wrap' }}>
        <span>Atenções e tarefas de hoje</span>
        {inProgressOrders.length > 0 && <span style={{ color: 'var(--primary)', fontSize: '14px' }}>{inProgressOrders.length} em andamento</span>}
      </h2>















      {loading ? (















        <p>Carregando ordens de manutenção...</p>















      ) : (















        <div className="asset-list">















          {overdueOrders.length === 0 && todayOrders.length === 0 ? (















            <div className="card" style={{ textAlign: 'center', padding: '40px', color: 'var(--text-muted)' }}>















              Nenhuma manutenção programada para hoje ou atrasada. Excelente trabalho!















            </div>















          ) : (















            <>















              {overdueOrders.slice(0, showAllOverdue ? overdueOrders.length : 5).map(order => (















                <div key={order.id} className="asset-row" style={{ borderLeft: '4px solid var(--danger)' }}>















                  <div>















                    <strong style={{ fontSize: '16px' }}>{order.asset.description}</strong>















                    <div style={{ fontSize: '14px', color: 'var(--text-muted)', marginTop: '4px' }}>















                      {describeAsset(order.asset)}
                      <br />
                      Identificação: {order.asset.patrimonio} · Prevista para: {formatPlannedDate(order.planned_date)}















                    </div>















                  </div>















                  <div style={{ display: 'flex', alignItems: 'center', gap: '16px' }}>















                    <span className="asset-badge stopped">Atrasada</span>















                    <button















                      className="btn btn-primary"















                      style={{ padding: '8px 16px', fontSize: '14px' }}















                      onClick={() => navigate(`/ordens/${order.id}/executar`)}















                    >















                      {order.status === 'in_progress' ? 'Continuar' : 'Iniciar'}















                    </button>















                  </div>















                </div>















              ))}































              {overdueOrders.length > 5 && (
                <button
                  type="button"
                  className="btn btn-secondary"
                  style={{ alignSelf: 'flex-start', marginBottom: '8px' }}
                  onClick={() => setShowAllOverdue((value) => !value)}
                >
                  {showAllOverdue ? 'Mostrar somente as 5 primeiras pendências' : `Ver todas as ${overdueOrders.length} pendências`}
                </button>
              )}

              {todayOrders.map(order => (















                <div key={order.id} className="asset-row" style={{ borderLeft: '4px solid var(--primary)' }}>















                  <div>















                    <strong style={{ fontSize: '16px' }}>{order.asset.description}</strong>















                    <div style={{ fontSize: '14px', color: 'var(--text-muted)', marginTop: '4px' }}>















                      {describeAsset(order.asset)}
                      <br />
                      Identificação: {order.asset.patrimonio} · <span style={{ fontWeight: '600' }}>{order.status === 'in_progress' || order.execution_status === 'in_progress' ? 'Em andamento' : 'Programada para hoje'}</span>















                    </div>















                  </div>















                  <div style={{ display: 'flex', alignItems: 'center', gap: '16px' }}>















                    <span className="asset-badge ok" style={{ backgroundColor: 'var(--primary-light)', color: 'var(--primary)' }}>Para Hoje</span>















                    <button















                      className="btn btn-primary"















                      style={{ padding: '8px 16px', fontSize: '14px' }}















                      onClick={() => navigate(`/ordens/${order.id}/executar`)}















                    >















                      {order.status === 'in_progress' ? 'Continuar' : 'Iniciar'}















                    </button>















                  </div>















                </div>















              ))}















            </>















          )}















        </div>















      )}































      {/* Execução de OM removida desta tela: a operação passa exclusivamente por ExecutarOM. */}


      {/* Modal para Registrar Ocorrência */}















      {showIssueModal && (















        <div className="overlay">















          <div className="modal-content">















            <h3 style={{ fontSize: '20px', fontWeight: '700' }}>Registrar ocorrência</h3>















            <form onSubmit={handleReportIssue} style={{ display: 'flex', flexDirection: 'column', gap: '16px' }}>















              <div className="form-group">















                <label className="form-label">Qual equipamento está envolvido?</label>















                <select className="form-control" value={selectedAsset} onChange={e => setSelectedAsset(e.target.value)} required>















                  <option value="">-- Escolha pelo setor, marca, modelo ou identificação --</option>















                  {operationalAssets.map(a => (















                    <option key={a.id} value={a.id}>















                      {a.patrimonio} · {a.description} · {a.sector?.name || 'Setor não informado'} · {[a.manufacturer, a.model].filter(Boolean).join(' ') || 'Marca/modelo não informado'}















                    </option>















                  ))}















                </select>
                {selectedIssueAsset && (
                  <div style={{ marginTop: '10px', padding: '10px 12px', borderRadius: '8px', background: 'var(--primary-light)', color: 'var(--text-main)', fontSize: '13px' }}>
                    <strong>Confirme antes de registrar:</strong> {selectedIssueAsset.description} · {selectedIssueAsset.sector?.name || 'Setor não informado'} · {[selectedIssueAsset.manufacturer, selectedIssueAsset.model].filter(Boolean).join(' ') || 'Marca/modelo não informado'} · Identificação {selectedIssueAsset.patrimonio}
                  </div>
                )}















              </div>































              <div className="form-group">















                <label className="form-label">Descreva o problema, risco ou necessidade encontrada</label>















                <textarea className="form-control" value={issueDesc} onChange={e => setIssueDesc(e.target.value)} placeholder="Ex: Vazamento de óleo na correia principal..." rows={3} required />















              </div>































              <div style={{ display: 'flex', alignItems: 'center', gap: '10px' }}>















                <input type="checkbox" id="stopMachine" checked={isStopped} onChange={e => setIsStopped(e.target.checked)} style={{ width: '20px', height: '20px' }} />















                <label htmlFor="stopMachine" style={{ fontWeight: '600', color: 'var(--danger)', cursor: 'pointer' }}>















                  Equipamento parado? Não utilizar até a liberação responsável.















                </label>















              </div>































              <div style={{ display: 'flex', gap: '12px', marginTop: '12px' }}>















                <button type="submit" className="btn btn-primary" style={{ flex: 1 }}>Registrar ocorrência</button>















                <button type="button" className="btn btn-secondary" onClick={() => setShowIssueModal(false)}>Cancelar</button>















              </div>















            </form>















          </div>















        </div>















      )}































      {/* Alerta de Sucesso Sincronização Foto */}















      {showSyncSuccess && (















        <div className="overlay">















          <div className="modal-content" style={{ textAlign: 'center', gap: '16px' }}>















            <CheckCircle size={48} style={{ color: 'var(--success)', margin: '0 auto' }} />















            <h3 style={{ fontSize: '20px', fontWeight: '700' }}>Formulário Lido com Sucesso!</h3>















            <p style={{ color: 'var(--text-muted)' }}>















              A foto da ordem nº 1004 foi analisada pela IA. Todos os 4 marcadores foram localizados e 100% das marcações foram reconhecidas.















            </p>















            <button className="btn btn-primary" onClick={() => setShowSyncSuccess(false)}>Excelente</button>















          </div>















        </div>















      )}















    </div>















  );















}
